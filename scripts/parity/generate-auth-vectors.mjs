// The R5 auth callback-page vectors, generated from the TypeScript reference itself.
//
// A module rather than a section of `generate-vectors.mjs`, on the pattern
// `generate-document-vectors.mjs` already set, so the vector has an entry point of its own AND a
// single definition. Both mattered here for the same reason.
//
// P9 found this vector on the regen path with a hand-copied duplicate of `src/auth.ts`'s `PAGE`
// template literal inline, under a description claiming it was "generated from the reference's own
// template literal". A colour changed in the built reference left `make parity-regen` at exit 0:
// the vector could not see the reference it names. Importing `PAGE` fixed that, but it left the
// CASE TABLE and the DESCRIPTION duplicated across two scripts that both wrote the same committed
// file — the identical failure one level up, with byte-identical output today binding nothing
// tomorrow, and the older script writing the committed path rather than regen's scratch. So there
// is now exactly one definition of the cases, the description and the import, and both entry
// points reach it.
//
//   node scripts/parity/generate-auth-vectors.mjs            # writes auth-pages.json
//   MCP_ROUTER_VECTORS=/tmp/x node scripts/parity/...         # writes it somewhere else

import { writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

export function writeAuthVectors({ write, distDir, require }) {
  // pin-class: src-export — auth.PAGE
  //
  // P11 annotated the region this replaces and carried it: `PAGE` was re-typed there, so the
  // class was declared and unmet. The carry closes here rather than in the gate alone — the
  // region now reaches `PAGE` through the require below, which is what `src-export` asserts.
  //
  // The template comes from the built reference, not from a copy of it. The require is the
  // assertion: if `PAGE` stops being exported, this throws rather than silently regenerating a
  // stale expectation, and `parity-regen-selftest` arm 7 proves that throw fires.
  const { PAGE } = require(join(distDir, 'auth.js'));
  if (typeof PAGE !== 'function') {
    throw new TypeError(
      `auth-pages: ${distDir}/auth.js does not export PAGE (got ${typeof PAGE}). The vector must ` +
      `be generated from the reference's own template literal, never from a copy of it.`
    );
  }

  const authCases = [
    { id: "connected",            kind: "connected", server: "linear",  detail: "",                     title: "linear is connected",  d: "You can close this tab and return to mcp-router." },
    { id: "connected-unicode",    kind: "connected", server: "a-b_9",   detail: "",                     title: "a-b_9 is connected",   d: "You can close this tab and return to mcp-router." },
    { id: "provider-refused",     kind: "failed",    server: "",        detail: "access_denied",        title: "Authorization failed", d: "access_denied" },
    { id: "no-code",             kind: "failed",    server: "",        detail: "the provider returned no code", title: "Authorization failed", d: "the provider returned no code" },
    { id: "exchange-failed",      kind: "failed",    server: "",        detail: "token endpoint returned 401 invalid_client", title: "Authorization failed", d: "token endpoint returned 401 invalid_client" },
    { id: "empty-error-detail",   kind: "failed",    server: "",        detail: "",                     title: "Authorization failed", d: "" },
  ];

  write("auth-pages", {
    description: "The bytes src/auth.ts's PAGE() emits, generated by importing the reference's own exported PAGE template literal from dist/auth.js. R4 diffs these.",
    cases: authCases.map(c => ({
      id: c.id,
      kind: c.kind,
      server: c.server,
      detail: c.detail,
      html: PAGE(c.title, c.d),
    }))
  });
}

// Run directly: build the same `write` the main generator uses, and the same output directory.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const require = createRequire(import.meta.url);
  const here = dirname(fileURLToPath(import.meta.url));
  const repoRoot = join(here, '..', '..');
  const distDir = process.env.MCP_ROUTER_DIST ?? join(repoRoot, 'dist');
  const outDir =
    process.env.MCP_ROUTER_VECTORS ?? join(repoRoot, 'app', 'Tests', 'RouterCoreTests', 'Vectors');
  mkdirSync(outDir, { recursive: true });
  const write = (name, payload) => {
    writeFileSync(join(outDir, `${name}.json`), JSON.stringify(payload, null, 2) + '\n');
    console.log(`${name}: ${payload.cases.length} cases`);
  };
  writeAuthVectors({ write, distDir, require });
}
