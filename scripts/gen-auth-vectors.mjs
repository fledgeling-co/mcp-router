import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

// PAGE is imported from the built reference, not copied from it. It used to be a verbatim copy
// carrying the comment "copied VERBATIM from src/auth.ts — these vectors are reference-derived":
// a copy is precisely what a reference-derived vector is not, and P9 measured the consequence on
// the sibling generator — a colour changed in the reference left `make parity-regen` green.
const require = createRequire(import.meta.url);
const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const distDir = process.env.MCP_ROUTER_DIST ?? join(repoRoot, 'dist');
const { PAGE } = require(join(distDir, 'auth.js'));
if (typeof PAGE !== 'function') {
  throw new TypeError(
    `gen-auth-vectors: ${distDir}/auth.js does not export PAGE (got ${typeof PAGE}). ` +
    `Run 'npm run build' first; never fall back to a transcribed copy.`
  );
}

const cases = [
  { id: "connected",            kind: "connected", server: "linear",  detail: "",                     title: "linear is connected",  d: "You can close this tab and return to mcp-router." },
  { id: "connected-unicode",    kind: "connected", server: "a-b_9",   detail: "",                     title: "a-b_9 is connected",   d: "You can close this tab and return to mcp-router." },
  { id: "provider-refused",     kind: "failed",    server: "",        detail: "access_denied",        title: "Authorization failed", d: "access_denied" },
  { id: "no-code",             kind: "failed",    server: "",        detail: "the provider returned no code", title: "Authorization failed", d: "the provider returned no code" },
  { id: "exchange-failed",      kind: "failed",    server: "",        detail: "token endpoint returned 401 invalid_client", title: "Authorization failed", d: "token endpoint returned 401 invalid_client" },
  { id: "empty-error-detail",   kind: "failed",    server: "",        detail: "",                     title: "Authorization failed", d: "" },
];

const out = {
  description: "The bytes src/auth.ts's PAGE() emits, generated by importing the reference's own exported PAGE template literal from dist/auth.js. R4 diffs these.",
  cases: cases.map(c => ({
    id: c.id,
    kind: c.kind,
    server: c.server,
    detail: c.detail,
    html: PAGE(c.title, c.d),
  })),
};
writeFileSync(join(repoRoot, 'app/Tests/RouterCoreTests/Vectors/auth-pages.json'), JSON.stringify(out, null, 2) + '\n');
console.log(`${out.cases.length} cases`);
